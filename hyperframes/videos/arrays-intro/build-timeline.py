"""Assemble the master narration, then write every timing the video uses.

Scene boundaries come from MEASURED clip durations. This script is the single
writer of timing: it emits scenes.json, generates timing.js (scene slots plus
scene-local word timings, read at runtime by the composition), and rewrites the
duration/start attributes in index.html and every compositions/sN.html. No
timing number is copied by hand anywhere — that copying is how a regenerated
voiceover silently desynced the video before.

It also refuses to assemble a clip that starts or ends hot (audiocheck.py):
butting such a clip against inserted silence is exactly what produced the
audible glitches, and this is the last point it can be caught.
"""
import json, os, re, subprocess, sys

from audiocheck import edge_report

here = os.path.dirname(os.path.abspath(__file__))
man = json.load(open(os.path.join(here, "audio", "manifest.json")))

LEAD, GAP, TAIL = 0.6, 0.45, 1.2   # breath in, between lines, and to let the last beat land

# ── guard: no hot edges ─────────────────────────────────────────────────────────
bad = [r for r in (edge_report(os.path.join(here, ln["file"])) for ln in man["lines"]) if not r["ok"]]
if bad:
    for r in bad:
        print(f"  {os.path.basename(r['path'])}: {'; '.join(r['problems'])}")
    sys.exit("refusing to assemble: clips above would click against the inserted silence. Re-run build-vo.py.")

# ── narration ──────────────────────────────────────────────────────────────────
# The concat DEMUXER needs identical codecs and rejects wav silence spliced
# between mp3 clips. The concat FILTER concatenates after decode.
# A scene's slot runs from the previous scene's end to its own end, so the
# first scene owns the lead-in silence. Starting scene 1 at LEAD instead left
# LEAD seconds of empty frames at the open and shifted all of scene 1 late.
# Word times are rebased from clip-local to scene-local by the line's offset
# inside its slot (LEAD for scene 1, 0 for the rest).
segs, scenes, t = [("sil", LEAD)], [], LEAD
for i, ln in enumerate(man["lines"]):
    slot_start = 0.0 if i == 0 else scenes[-1]["end"]
    line_start = round(t, 3)
    offset = round(line_start - slot_start, 3)
    segs.append(("file", os.path.join(here, ln["file"])))
    t += ln["duration"]
    pad = GAP if i < len(man["lines"]) - 1 else TAIL
    segs.append(("sil", pad)); t += pad
    end = round(t, 3)
    words = [{"w": w["w"], "s": round(w["s"] + offset, 3), "e": round(w["e"] + offset, 3)}
             for w in json.load(open(os.path.join(here, ln["words_file"])))]
    scenes.append({"scene": ln["line"], "title": ln["title"], "start": round(slot_start, 3),
                   "line_start": line_start, "end": end,
                   "duration": round(end - slot_start, 3), "vo": ln["text"], "words": words})
total = round(t, 3)

cmd, filt = ["ffmpeg", "-y", "-loglevel", "error"], []
for i, (kind, val) in enumerate(segs):
    if kind == "sil":
        cmd += ["-f", "lavfi", "-t", str(val), "-i", "anullsrc=r=44100:cl=mono"]
    else:
        cmd += ["-i", val]
    filt.append(f"[{i}:a]aresample=44100,aformat=sample_fmts=s16:channel_layouts=mono[a{i}]")
chain = "".join(f"[a{i}]" for i in range(len(segs)))
out = os.path.join(here, "audio", "narration.m4a")
cmd += ["-filter_complex", ";".join(filt) + f";{chain}concat=n={len(segs)}:v=0:a=1[out]",
        "-map", "[out]", "-c:a", "aac", "-b:a", "192k", "-ar", "44100", out]
subprocess.run(cmd, check=True)
probe = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                        "-of", "default=nw=1:nk=1", out], capture_output=True, text=True)
actual = round(float(probe.stdout.strip()), 3)

json.dump({"narration": "audio/narration.m4a", "planned_total": total, "measured_total": actual,
           "lead": LEAD, "gap": GAP, "tail": TAIL, "scenes": scenes},
          open(os.path.join(here, "scenes.json"), "w"), indent=2)

# ── timing.js: what the composition reads at runtime ───────────────────────────
payload = {"total": total,
           "scenes": [{"scene": s["scene"], "start": s["start"], "duration": s["duration"],
                       "words": s["words"]} for s in scenes]}
with open(os.path.join(here, "timing.js"), "w") as f:
    f.write("// GENERATED by build-timeline.py from the measured audio. Do not edit by hand.\n")
    f.write("window.AI_TIMING = " + json.dumps(payload) + ";\n")

# ── HTML attributes the runtime reads directly ─────────────────────────────────
def sub_once(path, pattern, repl, label):
    s = open(path).read()
    new, n = re.subn(pattern, repl, s, flags=re.S)
    if n != 1:
        sys.exit(f"timing sync failed: {label} matched {n} times in {os.path.basename(path)}")
    open(path, "w").write(new)

idx = os.path.join(here, "index.html")
sub_once(idx, r'(<div[^>]*?data-composition-id="arrays-intro"[^>]*?data-duration=")[0-9.]+(")',
         rf"\g<1>{total}\g<2>", "root duration")
for s in scenes:
    n = s["scene"]
    sub_once(idx, rf'(<div id="s{n}-host"[^>]*?data-start=")[0-9.]+("[^>]*?data-duration=")[0-9.]+(")',
             rf"\g<1>{s['start']}\g<2>{s['duration']}\g<3>", f"s{n} host")
    sub_once(os.path.join(here, "compositions", f"s{n}.html"),
             rf'(<div id="s{n}-root"[^>]*?data-duration=")[0-9.]+(")',
             rf"\g<1>{s['duration']}\g<2>", f"s{n} root")

for s in scenes:
    print(f'  scene {s["scene"]}  {s["start"]:>6.2f} → {s["end"]:>6.2f}  ({s["duration"]:>5.2f}s)  {len(s["words"]):>2} words  {s["title"]}')
print(f"\nplanned {total}s · measured narration {actual}s · timing.js + 17 HTML timing attributes written")
