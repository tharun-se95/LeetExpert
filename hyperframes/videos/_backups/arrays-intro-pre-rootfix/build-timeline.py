"""Assemble the master narration and emit exact scene timings.

Scene boundaries come from MEASURED clip durations, never from the script's
word-count estimate — the composition is synced to the audio that actually
exists.
"""
import json, os, subprocess

here = os.path.dirname(os.path.abspath(__file__))
man = json.load(open(os.path.join(here, "audio", "manifest.json")))

LEAD, GAP, TAIL = 0.6, 0.45, 1.2   # breath in, between lines, and to let the last beat land

# The concat DEMUXER needs identical codecs and rejects wav silence spliced
# between mp3 clips. The concat FILTER concatenates after decode, so silence
# generated by lavfi and the mp3s can be joined in one pass.
segs, scenes, t = [], [], LEAD
segs.append(("sil", LEAD))
for i, ln in enumerate(man["lines"]):
    start = round(t, 3)
    segs.append(("file", os.path.join(here, ln["file"])))
    t += ln["duration"]
    if i < len(man["lines"]) - 1:
        segs.append(("sil", GAP)); t += GAP
        end = round(t, 3)
    else:
        segs.append(("sil", TAIL)); t += TAIL
        end = round(t, 3)
    scenes.append({
        "scene": ln["line"], "title": ln["title"],
        "start": start, "end": end, "duration": round(end - start, 3),
        "vo": ln["text"],
    })
total = round(t, 3)

cmd, filt = ["ffmpeg", "-y", "-loglevel", "error"], []
for i, (kind, val) in enumerate(segs):
    if kind == "sil":
        cmd += ["-f", "lavfi", "-t", str(val), "-i", "anullsrc=r=44100:cl=mono"]
    else:
        cmd += ["-i", val]
    filt.append(f"[{i}:a]aresample=44100,aformat=sample_fmts=s16:channel_layouts=mono[a{i}]")
chain = "".join(f"[a{i}]" for i in range(len(segs)))
filter_complex = ";".join(filt) + f";{chain}concat=n={len(segs)}:v=0:a=1[out]"
out = os.path.join(here, "audio", "narration.m4a")
cmd += ["-filter_complex", filter_complex, "-map", "[out]",
        "-c:a", "aac", "-b:a", "192k", "-ar", "44100", out]
subprocess.run(cmd, check=True)

probe = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                        "-of", "default=nw=1:nk=1", out], capture_output=True, text=True)
actual = round(float(probe.stdout.strip()), 3)

json.dump({"narration": "audio/narration.m4a", "planned_total": total,
           "measured_total": actual, "lead": LEAD, "gap": GAP, "tail": TAIL,
           "scenes": scenes},
          open(os.path.join(here, "scenes.json"), "w"), indent=2)

for s in scenes:
    print(f'  scene {s["scene"]}  {s["start"]:>6.2f} → {s["end"]:>6.2f}  ({s["duration"]:>5.2f}s)  {s["title"]}')
print(f'\nplanned {total}s · measured narration {actual}s')

